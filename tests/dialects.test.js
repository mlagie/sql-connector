describe("migration dialect implementations", () => {
    test("maps MySQL types and builds schema SQL", async () => {
        const dialect = new MySQLDialect();
        expect(dialect.placeholder()).toBe("?");
        await expect(dialect.execute({
            query: (sql, values, callback) => callback(null, [{ id: 1 }])
        }, "SELECT ?", [1])).resolves.toEqual([{ id: 1 }]);
        await expect(dialect.execute({
            query: (sql, values, callback) => callback(new Error("query failed"))
        }, "SELECT ?", [1])).rejects.toThrow("query failed");
        await expect(dialect.execute({
            promise: () => ({ query: jest.fn().mockResolvedValue([[{ id: 2 }]]) })
        }, "SELECT ?", [1])).resolves.toEqual([{ id: 2 }]);
        await expect(dialect.execute({
            promise: () => ({ query: jest.fn().mockResolvedValue([[{ id: 3 }]]) })
        }, "SELECT 1")).resolves.toEqual([{ id: 3 }]);
        for (const [type, expected] of MYSQL_TYPES) expect(dialect.mapType({ type, length: 10 })).toBe(expected);
        expect(() => dialect.mapType({ type: "unknown" })).toThrow("Unsupported MySQL type");
        expect(() => dialect.mapType({})).toThrow("Unsupported MySQL type: undefined");
        expect(dialect.defaultSql(undefined)).toBe("");
        expect(dialect.defaultSql(null)).toBe("DEFAULT NULL");
        expect(dialect.defaultSql(2)).toBe("DEFAULT 2");
        expect(dialect.defaultSql(true)).toBe("DEFAULT 1");
        expect(dialect.defaultSql(false)).toBe("DEFAULT 0");
        expect(dialect.defaultSql("O'Reilly")).toBe("DEFAULT 'O''Reilly'");
        expect(dialect.defaultSql("CURRENT_DATE")).toBe("DEFAULT CURRENT_DATE");
        expect(dialect.defaultSql({ value: 1 })).toContain("DEFAULT");
        const field = { type: "string", length: 20, required: true, default: "x", unique: true, customize: "CHECK (1)" };
        expect(dialect.columnDefinition("name", field)).toContain("`name` VARCHAR(20) NOT NULL");
        expect(() => dialect.columnDefinition("id", { type: "int", primary_key: true, unique: true })).toThrow();
        expect(dialect.columnDefinition("id", { type: "int", primary_key: true, auto_increment: true })).toContain("AUTO_INCREMENT PRIMARY KEY");
        expect(dialect.createTable("users", { id: { type: "int", primary_key: true }, user_id: { type: "int", foreignKey: "users(id)" } })).toContain("FOREIGN KEY");
        expect(dialect.createTable("users", { user_id: { type: "int", foreignKey: "users.id" } })).toContain("FOREIGN KEY");
        expect(() => dialect.createTable("users", { user_id: { type: "int", foreignKey: "invalid key" } })).toThrow();
        expect(dialect.alterColumn("users", "name", { type: "string" })).toContain("MODIFY COLUMN");
        expect(dialect.introspectionQueries().columns).toContain("ORDINAL_POSITION");
        expect(dialect.normalizeDatabaseColumn({ data_type: "varchar", character_maximum_length: 10, is_nullable: "NO", column_key: "PRI", extra: "auto_increment", column_default: "x" })).toEqual(expect.objectContaining({ type: "varchar", length: 10, required: true, primary_key: true, auto_increment: true }));
        expect(dialect.normalizeDatabaseColumn({})).toEqual(expect.objectContaining({ type: "", length: undefined, auto_increment: false }));
        expect(dialect.createMigrationTable()).toContain("sql_connector_migrations");
        expect(dialect.insertMigration()).toContain("VALUES (?, ?, ?, ?)");
        expect(dialect.selectMigrations()).toContain("ORDER BY");
        expect(dialect.deleteMigration()).toContain("WHERE");
    });

    test("maps PostgreSQL types and builds schema SQL", async () => {
        const dialect = new PostgreSQLDialect();
        expect(dialect.placeholder(2)).toBe("$3");
        for (const [type, expected] of POSTGRES_TYPES) expect(dialect.mapType({ type, length: 10 })).toBe(expected);
        expect(() => dialect.mapType({ type: "unknown" })).toThrow("Unsupported PostgreSQL type");
        expect(() => dialect.mapType({})).toThrow("Unsupported PostgreSQL type: undefined");
        expect(dialect.defaultSql(undefined)).toBe("");
        expect(dialect.defaultSql(null)).toBe("DEFAULT NULL");
        expect(dialect.defaultSql(2)).toBe("DEFAULT 2");
        expect(dialect.defaultSql(false)).toBe("DEFAULT FALSE");
        expect(dialect.defaultSql(true)).toBe("DEFAULT TRUE");
        expect(dialect.defaultSql("O'Reilly")).toBe("DEFAULT 'O''Reilly'");
        expect(dialect.defaultSql("CURRENT_TIME")).toBe("DEFAULT CURRENT_TIME");
        expect(dialect.defaultSql({ value: 1 })).toContain("DEFAULT");
        expect(dialect.columnDefinition("id", { type: "int", primary_key: true, auto_increment: true, customize: "CHECK (id > 0)" })).toContain("CHECK (id > 0)");
        expect(dialect.columnDefinition("name", { type: "string", default: "x", unique: true })).toContain("UNIQUE");
        expect(() => dialect.columnDefinition("id", { type: "int", primary_key: true, unique: true })).toThrow();
        expect(dialect.createTable("users", { name: { type: "string" }, user_id: { type: "int", foreignKey: "users.id" } })).toContain("FOREIGN KEY");
        expect(() => dialect.createTable("users", { user_id: { type: "int", foreignKey: "invalid key" } })).toThrow();
        expect(dialect.alterColumn("users", "name", { type: "string", required: true, default: "x" })).toContain("SET NOT NULL");
        expect(dialect.alterColumn("users", "name", { type: "string" })).toContain("DROP NOT NULL");
        expect(dialect.introspectionQueries().columns).toContain("ordinal_position");
        expect(dialect.normalizeDatabaseColumn({ udt_name: "int4", is_nullable: "NO", column_default: "nextval('x')" })).toEqual(expect.objectContaining({ type: "int4", required: true, auto_increment: true }));
        expect(dialect.normalizeDatabaseColumn({ data_type: "varchar", column_default: null })).toEqual(expect.objectContaining({ type: "varchar", auto_increment: false }));
        expect(dialect.normalizeDatabaseColumn({})).toEqual(expect.objectContaining({ type: "", auto_increment: false }));
        expect(dialect.createMigrationTable()).toContain("TIMESTAMPTZ");
        expect(dialect.insertMigration()).toContain("VALUES ($1, $2, $3, $4)");
        expect(dialect.selectMigrations()).toContain("ORDER BY");
        expect(dialect.deleteMigration()).toContain("WHERE");
        expect(() => dialect.execute({}, "SELECT 1")).toThrow("does not expose query");
        await expect(dialect.execute({ query: jest.fn().mockResolvedValue({ rows: [{ id: 1 }] }) }, "SELECT 1")).resolves.toEqual([{ id: 1 }]);
    });
});

describe("createDialect", () => {
    test("creates supported aliases and rejects unknown dialects", () => {
        expect(createDialect("mysql")).toBeInstanceOf(MySQLDialect);
        expect(createDialect("mariadb")).toBeInstanceOf(MySQLDialect);
        expect(createDialect("postgres")).toBeInstanceOf(PostgreSQLDialect);
        expect(createDialect("postgresql")).toBeInstanceOf(PostgreSQLDialect);
        expect(createDialect("POSTGRES")).toBeInstanceOf(PostgreSQLDialect);
        setGlobalDialect("postgres");
        expect(createDialect()).toBeInstanceOf(PostgreSQLDialect);
        expect(() => createDialect("sqlite")).toThrow("Unsupported migration dialect");
    });
});